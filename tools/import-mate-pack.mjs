// Replace the entire mate-in-one pool only after validating the complete pack.
// node tools/import-mate-pack.mjs data/mate-in-1-500.json > src/data/puzzles-mate.ts
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import { Chess } from 'chessops/chess';
import { parseFen } from 'chessops/fen';
import { makeUci, parseUci } from 'chessops/util';
import { makeSan } from 'chessops/san';

const pack = JSON.parse(readFileSync(process.argv[2], 'utf8'));
assert.equal(pack.puzzles.length, 500);
const ids = new Set();
const positions = new Set();
const counts = { white: 0, black: 0 };
const puzzles = pack.puzzles.map((p) => {
  const pos = Chess.fromSetup(parseFen(p.fen).unwrap()).unwrap();
  assert.equal(p.sideToMove, pos.turn);
  assert.equal(p.boardOrientation, pos.turn);
  const signature = p.fen.split(' ').slice(0, 4).join(' ');
  assert(!positions.has(signature), `Duplicate position ${p.id}`);
  assert(!ids.has(p.id), `Duplicate id ${p.id}`);
  positions.add(signature);
  ids.add(p.id);
  counts[pos.turn]++;
  const solution = parseUci(p.solutionUci);
  assert(solution && pos.isLegal(solution), `Illegal solution ${p.id}`);
  assert.equal(makeSan(pos, solution), p.solutionSan);
  const mates = [];
  for (const [from, tos] of pos.allDests()) {
    for (const to of tos) {
      const promotions = pos.board.get(from)?.role === 'pawn' && [0, 7].includes(to >> 3)
        ? ['queen', 'rook', 'bishop', 'knight'] : [undefined];
      for (const promotion of promotions) {
        const move = promotion ? { from, to, promotion } : { from, to };
        if (!pos.isLegal(move)) continue;
        const after = pos.clone();
        after.play(move);
        if (after.isCheckmate()) mates.push(makeUci(move));
      }
    }
  }
  assert.deepEqual(mates, [p.solutionUci], `Non-unique/wrong mate ${p.id}`);
  return { id: `MZ500-${String(p.id).padStart(4, '0')}`, fen: p.fen,
    uci: p.solutionUci, san: p.solutionSan, themes: ['mate', 'mateIn1', 'oneMove', 'uniqueSolution'] };
});
assert.deepEqual(counts, { white: 250, black: 250 });
console.error('Validated 500 unique positions and unique mating moves: 250 white / 250 black.');
process.stdout.write(`/** User pack mate_in_1_500_orientation_safe.zip; replaces all previous mate tasks.
 * Generated by tools/import-mate-pack.mjs. Side and orientation come from FEN. */
export interface MatePuzzle {
  id: string;
  fen: string;
  uci: string;
  san: string;
  themes: string[];
}
export const MATE_PUZZLES: MatePuzzle[] = ${JSON.stringify(puzzles, null, 2)};
`);
